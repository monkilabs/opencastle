/** OpenCastle project manifest (.opencastle.json). */
export interface Manifest {
  version: string;
  ide: string;
  ides?: string[];
  installedAt: string;
  updatedAt: string;
  managedPaths?: ManagedPaths;
  stack?: StackConfig;
  repoInfo?: RepoInfo;
}

/** Framework vs customizable file paths. */
export interface ManagedPaths {
  /** Wholly generated. Safe to delete and regenerate. */
  framework: string[];
  /** The user's, never overwritten. */
  customizable: string[];
  /**
   * Co-owned: the user's prose plus a managed block. Never delete these — strip
   * the block and keep the rest. Treating them as `framework` is what let
   * `init` and `remove --all` destroy someone's CLAUDE.md.
   */
  merged?: string[];
}

/** Structure check for the doctor command — describes expected files/dirs per IDE. */
export interface DoctorCheck {
  /** Human-friendly label for the check */
  label: string;
  /** Relative path to a file or directory (ending with /) to check exists */
  path: string;
  /** 'file' or 'dir' */
  type: 'file' | 'dir';
  /** If true, counts the contents and reports count */
  countContents?: boolean;
  /** File extension filter when counting (e.g. '.md', '.mdc', '.agent.md') */
  countFilter?: string;
}

