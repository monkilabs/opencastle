/** Results from a copy/install/update operation. */
export interface CopyResults {
  copied: string[];
  skipped: string[];
  created: string[];
  /** Root files replaced wholesale on upgrade; each has a `.opencastle-backup`. */
  adopted?: string[];
  /** Root files that still carry an older release's output above our block. */
  staleRoots?: string[];
  /** Files the compiler removed that it did not generate. */
  deleted?: string[];
  /**
   * Generated config files that exist but will not parse.
   *
   * Named and skipped rather than thrown: an abort here leaves the framework
   * tree written and the manifest absent, and the user is never told which
   * file to fix.
   */
  /**
   * Files that held more than one complete block and were collapsed to one.
   *
   * Distinct from `adopted`: nothing here came from an earlier release, so
   * reporting it as "replaced a file generated by an earlier version" told the
   * user the wrong story about their own file. A backup is written either way.
   */
  repaired?: string[];

  /**
   * Root files holding more than one block *and* unpaired markers.
   *
   * Not reducible without risking the user's own text, so they are named and
   * left alone rather than cut.
   */
  damagedRoots?: string[];

  unreadable?: string[];

  /**
   * Every destination the compile considered, whatever it then did to it.
   *
   * The sweep that removes output with no source left needs "did the compiler
   * account for this path", and reassembling that from created ∪ copied ∪
   * skipped makes it depend on how each write happened to be *categorised*. It
   * broke twice that way: once when `skipped` was left out of the union and the
   * first sync deleted all 79 regenerated files, once when `copied` was left
   * out and an upgrade deleted 43 skills. Recorded where the path is decided,
   * so no reporting change can move it.
   */
  visited?: string[];
  /**
   * Root files carrying a marker that belongs to no block.
   *
   * Distinct from `staleRoots`: a hand-written file that merely quotes the
   * marker has never held our output, and saying it "still contains output from
   * an earlier version" is simply false.
   */
  tornRoots?: string[];
}

