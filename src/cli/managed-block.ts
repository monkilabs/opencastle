import { readFile, writeFile, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'

/**
 * Merge generated content into a file the user may already own.
 *
 * Root instruction files — CLAUDE.md, AGENTS.md, GEMINI.md,
 * .github/copilot-instructions.md — are the one place where the user's own
 * writing and the compiler's output share a file. The adapters used to resolve
 * that by skipping: if the file existed, nothing was written. On the exact repo
 * this tool is pitched at — one that already has a CLAUDE.md — that meant the
 * instructions layer silently never installed.
 *
 * A marked block fixes both halves. The user's content is never touched, and
 * the generated section can be replaced on every sync without diffing prose.
 * Same convention as the .gitignore block, so there is one idea to learn.
 */

export const BLOCK_START = '<!-- >>> OpenCastle managed — regenerated by `opencastle sync`, edits here are lost >>> -->'
export const BLOCK_END = '<!-- <<< OpenCastle managed <<< -->'

/**
 * Co-owned files are read and written as bytes, not as UTF-8 text.
 *
 * Everything outside our markers belongs to the user, including bytes that are
 * not valid UTF-8. Decoding replaced each of them with U+FFFD and the encode on
 * the way out made that permanent: `Café rules` came back as `Caf<EF BF BD>
 * rules`, and in `.gitignore` a rule containing such a byte stopped matching —
 * so the path it protected became committable, silently, with no backup.
 *
 * `latin1` is a byte-for-byte codec: one byte in, one code unit out, and back
 * again unchanged whatever the bytes were. All the surgery here is offsets and
 * ASCII-ish markers, so it works the same in that space — the markers just have
 * to be converted too, since ours contains an em dash.
 */
const BLOCK_START_BYTES = Buffer.from(BLOCK_START, 'utf8').toString('latin1')
const BLOCK_END_BYTES = Buffer.from(BLOCK_END, 'utf8').toString('latin1')

/** Text we generated, as the bytes it should occupy on disk. */
function asBytes(text: string): string {
  return Buffer.from(text, 'utf8').toString('latin1')
}

async function readBytes(path: string): Promise<string> {
  return (await readFile(path)).toString('latin1')
}

async function writeBytes(path: string, bytes: string): Promise<void> {
  await writeFile(path, Buffer.from(bytes, 'latin1'))
}

export type MergeAction =
  | 'created'
  | 'updated'
  | 'appended'
  | 'adopted'
  /** The end marker was missing; the block was rebuilt and the old file backed up. */
  | 'repaired'
  | 'unchanged'

export interface MergeResult {
  action: MergeAction
  /** True when the file held content the user wrote. */
  preservedUserContent: boolean
  /**
   * The file keeps output from an older release above our block, which we could
   * not safely remove because the user's own writing came first.
   */
  staleGeneratedContent?: boolean
  /** The file carries a start marker that opens no block. */
  orphanMarker?: boolean
  /**
   * More than one complete block *and* unpaired markers.
   *
   * The tool will not reduce this: cutting a block here can promote two strays
   * into a pair around the user's own text. Reported so a person can resolve it,
   * which is the same answer this module gives to any damage it cannot read.
   */
  damaged?: boolean
}

/**
 * Fingerprints of a root file that an OpenCastle release before the markers
 * generated in full.
 *
 * Without this, every existing install's first `sync` would treat its own old
 * output as the user's writing, keep it, and append a second copy underneath —
 * leaving a doubled file whose stale half still advertises agents and skills
 * that no longer exist. These strings only ever came out of this tool.
 */
/**
 * Sentences those releases opened their *body* with. Prose no one writes by
 * accident, and never as a note to a teammate.
 */
const LEGACY_GENERATED_MARKERS = [
  'All conventions, architecture, and project context are embedded below',
  'All conventions, architecture, and project context live in',
]

/**
 * The banner those releases wrote, which only counts inside an HTML comment.
 *
 * `This file is managed by OpenCastle` is a sentence a person writes — "This
 * file is managed by OpenCastle. Make your edits in `.opencastle/` instead." is
 * a reasonable line for a human to put at the top of their own CLAUDE.md, and
 * it was enough to have that file replaced wholesale. Our releases only ever
 * emitted it as `<!-- ⚠️ This file is managed by OpenCastle. … -->`, so the
 * comment is the part that makes it ours.
 */
const LEGACY_BANNER_MARKERS = ['This file is managed by OpenCastle']

/** Headers those releases opened the file with. */
const LEGACY_GENERATED_HEADERS = ['# Project Instructions', '# Copilot Instructions']

/**
 * A leading byte-order mark, removed before any of these predicates look.
 *
 * In byte space a BOM is three characters in front of the heading, so
 * `# Project Instructions` stopped being the first line and every legacy test
 * silently answered no: an upgrade neither adopted the file nor warned about
 * it, just appended — 197 lines becoming 421, in silence — while `doctor`, still
 * decoding as UTF-8 where the BOM is one invisible character, said the opposite
 * about the same bytes. A one-byte cliff, and a fresh pair of interpreters.
 */
const BOM_BYTES = Buffer.from('\ufeff', 'utf8').toString('latin1')

function withoutBom(text: string): string {
  if (text.startsWith(BOM_BYTES)) return text.slice(BOM_BYTES.length)
  return text.startsWith('\ufeff') ? text.slice(1) : text
}

/** First line with content, ignoring comments that are not our own banner. */
function firstMeaningfulLine(content: string): string {
  for (const raw of withoutBom(content).split('\n')) {
    const line = raw.trim()
    if (!line) continue
    if (line.startsWith('<!--')) {
      if ([...LEGACY_GENERATED_MARKERS, ...LEGACY_BANNER_MARKERS].some((m) => line.includes(m))) {
        return line
      }
      continue
    }
    return line
  }
  return ''
}

/**
 * True only when the file is generated all the way through.
 *
 * Matching a fingerprint anywhere is not enough, in two directions. People edit
 * their generated CLAUDE.md to add house rules at the top — adopting that file
 * deletes the rules, which is the loss the markers exist to prevent wearing a
 * narrower disguise. And a hand-written file can quote "This file is managed by
 * OpenCastle" in a note to teammates without being ours at all. A file that
 * opens with someone else's writing is theirs: the block is appended instead,
 * and the stale generated text stays visible, which is untidy but recoverable.
 */
function looksLikeLegacyGenerated(
  content: string,
  start = BLOCK_START,
  end = BLOCK_END,
): boolean {
  // A marker anywhere disqualifies the file, which is what the comment above
  // has always claimed and what the code did not do.
  //
  // The fingerprints below are byte-for-byte the *current* release's own output
  // — they have to be, or an upgrade would not recognise its predecessor — so
  // "starts with our header and contains our phrase" is true of every file this
  // tool has ever written, including one whose start marker a merge dropped
  // yesterday. The old gate only asked whether a *complete* block was present.
  // A torn file therefore looked pre-marker, was replaced wholesale, and the
  // notes the user had added below the block went with it. The surviving end
  // marker said exactly where our half stopped and was thrown away.
  //
  // Adoption is for a file with no markers at all. Anything else has a boundary
  // we can read, and reading it is always better than guessing.
  // Markers passed in, not defaulted. The callers work in byte space (see
  // `asBytes`) and our start marker contains an em dash, so the defaults match
  // nothing there — the gate silently passed and a file with a stray marker was
  // adopted and deleted. A guard that cannot fire is worse than none, because
  // the comment above says it did.
  if (blockRegions(content, start, end).length > 0) return false
  if (orphanMarkers(content, start, end).length > 0) return false
  // The phrase has to *open a line*, not merely appear.
  //
  // Our old output began the sentence; a note to teammates does not — "Heads-up
  // for new joiners: This file is managed by OpenCastle, so make your edits in
  // .opencastle/" is a hand-written file that the substring test called ours
  // and replaced wholesale. The heading alone is not a fingerprint either:
  // `# Project Instructions` is a heading a person might reasonably write.
  // Normalised the same way, so the banner comment our old releases opened
  // with is recognised while a sentence that merely mentions us is not.
  const first = firstMeaningfulLine(content)
  const firstOpener = first.replace(/^<!--\s*/, '').replace(/^[^A-Za-z#]+/, '')
  const startsGenerated =
    LEGACY_GENERATED_HEADERS.includes(first) ||
    [...LEGACY_GENERATED_MARKERS, ...LEGACY_BANNER_MARKERS].some((m) => firstOpener.startsWith(m))
  return startsGenerated && hasLegacyOpeningLine(content)
}

/**
 * Does some line *open* with one of the phrases those releases wrote?
 *
 * Opening, not merely containing. Our old output either began the line with the
 * phrase or put it alone in a banner comment; a note to teammates has it in the
 * middle of a sentence — "Heads-up for new joiners: This file is managed by
 * OpenCastle, so make your edits in `.opencastle/`" — and the substring test
 * called that file ours and replaced it wholesale.
 *
 * The banner is why a bare `startsWith` on the trimmed line is not enough: the
 * real one reads `<!-- ⚠️ This file is managed by OpenCastle. … -->`, so the
 * comment opener and any decoration in front of the words come off first.
 */
function hasLegacyOpeningLine(content: string): boolean {
  return withoutBom(content).split('\n').some((line) => {
    const trimmed = line.trim()
    const inComment = trimmed.startsWith('<!--')
    const opener = trimmed.replace(/^<!--\s*/, '').replace(/^[^A-Za-z#]+/, '')
    if (LEGACY_GENERATED_MARKERS.some((m) => opener.startsWith(m))) return true
    return inComment && LEGACY_BANNER_MARKERS.some((m) => opener.startsWith(m))
  })
}

/**
 * Does this text carry a whole generated body from an older release?
 *
 * Both halves are required: a line that is one of our old headers, *and* one of
 * the phrases those releases wrote underneath it. Either alone is wrong in a
 * direction that has already shipped.
 *
 * Testing the phrase anywhere fired on a file that merely mentioned OpenCastle
 * in a note to teammates. Testing only the *first* line — the correction — was
 * worse, because the population this exists for is exactly the one whose first
 * line is not ours: someone who added their own rules above the generated text
 * and then upgraded. For them the predicate was false, so the warning never
 * came, and their root file quietly ended up holding the previous release's
 * whole instruction set above the new one, with `doctor`, `sync --check` and
 * `status` all reporting health. Meanwhile it fired falsely on any file whose
 * first heading happened to read `# Project Instructions`, telling that user to
 * "delete everything above the OpenCastle block that you did not write" — every
 * byte of which was theirs.
 *
 * Requiring both is what separates a file that contains our old output from one
 * that talks about it.
 */
export function carriesLegacyBody(content: string): boolean {
  const lines = withoutBom(content).split('\n').map((l) => l.trim())
  const hasHeader = lines.some((l) => LEGACY_GENERATED_HEADERS.includes(l))
  return hasHeader && hasLegacyOpeningLine(content)
}

/** Extract whatever sits outside the managed block. */
export function stripManagedBlock(content: string): string {
  return stripAllBlocks(content)
}

/** Line-start offsets of every occurrence of `marker`, at column 0. */
function markerOffsets(content: string, marker: string): number[] {
  const out: number[] = []
  let from = 0
  for (;;) {
    const at = content.indexOf(marker, from)
    if (at === -1) return out
    if (at === 0 || content[at - 1] === '\n') out.push(at)
    from = at + marker.length
  }
}

export interface BlockRegion {
  /** Offset of BLOCK_START. */
  start: number
  /** Offset just past BLOCK_END. */
  end: number
}

/**
 * Every *complete* block in the file, in order.
 *
 * Complete means a start marker with an end marker after it and no second start
 * marker in between. A lone start marker is not a block and is deliberately not
 * treated as one: two readers disagreed about what it meant — the writer took
 * everything below it as ours and discarded it, the remover took only the marker
 * line — so one deleted line could either weld a stale 20KB body into the user's
 * file forever or delete prose the user had written below a marker they had
 * merely quoted. Neither reading is safe when we cannot tell which is true, so
 * the ambiguity is reported by `orphanMarkers` and acted on by nobody.
 *
 * No markdown analysis. Four rounds went into guessing, from the prose around a
 * marker, whether it was ours; each guess was wrong somewhere, and every mistake
 * ended the same way — conclude there is no block, append another, grow by 20KB
 * a sync. The invariant is enforced instead: exactly one complete block per file.
 */
export function blockRegions(
  content: string,
  startMarker: string = BLOCK_START,
  endMarker: string = BLOCK_END,
): BlockRegion[] {
  const starts = markerOffsets(content, startMarker)
  const ends = markerOffsets(content, endMarker)
  const regions: BlockRegion[] = []

  for (const [i, start] of starts.entries()) {
    const next = starts[i + 1] ?? Infinity
    const end = ends.find((e) => e > start && e < next)
    if (end !== undefined) regions.push({ start, end: end + endMarker.length })
  }
  return regions
}

/** Markers that belong to no block — damage, reported rather than interpreted. */
export function orphanMarkers(
  content: string,
  startMarker: string = BLOCK_START,
  endMarker: string = BLOCK_END,
): number[] {
  // Both orientations. Tracking only unmatched *starts* meant a file torn the
  // other way — end marker surviving, start deleted — was never named by
  // `doctor` and kept its whole generated body through an uninstall, while the
  // `.gitignore` remover swept stray end markers all along. One format, two
  // readers, again.
  const regions = blockRegions(content, startMarker, endMarker)
  const claimedStarts = new Set(regions.map((r) => r.start))
  const claimedEnds = new Set(regions.map((r) => r.end - endMarker.length))
  return [
    ...markerOffsets(content, startMarker).filter((at) => !claimedStarts.has(at)),
    ...markerOffsets(content, endMarker).filter((at) => !claimedEnds.has(at)),
  ].sort((a, b) => a - b)
}

/** How long the marker at `at` is — start and end markers differ in length. */
function markerLengthAt(content: string, at: number, start: string, end: string): number {
  return content.startsWith(start, at) ? start.length : end.length
}

/** Cut a region out, taking back the newline on each side. Shared with gitignore. */
export function cutBlockRegion(content: string, start: number, end: number): string {
  return cutBlock(content, start, end)
}

/** Cut a marker line out, taking back only its own terminator. */
export function cutMarkerLine(content: string, start: number, end: number): string {
  return cutLine(content, start, end)
}

/**
 * Every complete block in the file. All of them are ours.
 *
 * There is no fence reading here, and the absence is the design.
 *
 * Six review rounds each produced a new way for a "is the user merely quoting
 * this?" test to be wrong, and the failures were never small. Fence-adjacency,
 * closed-pair scanning, masked-region scanning, and "the pair contains nothing
 * but blocks" each fixed the previous one's counterexample and shipped its own.
 * Between them they managed to: disown a block mid-file so `sync --check` went
 * permanently red on a remedy that cleared nothing; let an upgrade append a
 * *second* complete 20KB block that `--check`, `doctor` and `status` all called
 * healthy, because the checker counted owned regions and agreed there was one;
 * leave our entire body in the user's file after `remove --all`; and overwrite
 * a line of the user's own prose whenever it shared a fence with the markers.
 * Every one of those was a file an ordinary edit could produce.
 *
 * The markers are the contract, and they say so in their own text —
 * "regenerated by `opencastle sync`, edits here are lost". A complete pair is
 * this tool's, wherever it sits. Someone documenting the convention in a fenced
 * example has that example's body regenerated, or removed as a duplicate with a
 * backup written and a line of output saying so; their prose, their fence and
 * their headings are untouched. That is a cost paid by about one repository, in
 * exchange for the writer, the drift checker, the collapse and the uninstall
 * finally sharing one reading of the word "ours".
 */
export function ownedRegions(content: string): BlockRegion[] {
  return blockRegions(content)
}

/** The region we maintain: the last one, since every complete pair is ours. */
function maintainedRegion(content: string): BlockRegion | null {
  const owned = ownedRegions(content)
  return owned.length === 0 ? null : owned[owned.length - 1]
}

function findBlockStart(content: string): number {
  return maintainedRegion(content)?.start ?? -1
}

/**
 * Cut a block out, taking back only the newline that is certainly ours.
 *
 * The append path writes one newline between the user's content and the block,
 * and the block ends with one. Reclaiming both unconditionally was wrong the
 * moment a file held two blocks: the newline before the *second* one belongs to
 * whatever precedes it, so taking it welded two lines together. In `.gitignore`
 * that turned `.env.local` into part of a comment and stopped it being ignored;
 * in a root file it moved the start marker off column 0, after which
 * `blockRegions` found nothing while `hasManagedBlock` had already said yes, and
 * `sync` threw — having already deleted the framework directories, so the
 * install was left gutted.
 *
 * The block's own trailing newline is always ours. The one before it is taken
 * only when doing so cannot join two lines: when nothing follows, or when what
 * follows starts on its own line anyway.
 */
function cutBlock(content: string, start: number, end: number): string {
  const before = content.slice(0, start)
  const after = content.slice(end).replace(/^\r?\n/, '')

  // Take back the blank line above the block, and only that.
  //
  // The append path writes `<their content>\n` before the block, so when their
  // file ended in a newline the result has a blank line there — one we made,
  // and one that has to go or every install/uninstall cycle adds another.
  //
  // The previous rule was "a newline, if what follows is empty or blank", which
  // is the same text in two different situations. A file whose block was not
  // placed by our append — merged in, hand-moved, written by a release from
  // before the markers — has an ordinary line terminator there, belonging to
  // the user, and we took it: `mine\n<block>` came back as `mine`, and
  // `a\n<block>\n\nb\n` lost the blank line between a and b.
  //
  // Requiring a *blank* line narrows it to what we can actually recognise as
  // ours. The one shape it gets wrong now is the reverse: a file that ended
  // without a trailing newline gains one, because our append and a hand-placed
  // block are byte-identical in that case and nothing in the file can tell them
  // apart. Leaving a newline behind is the better half of an undecidable trade
  // than deleting one of theirs.
  //
  // It cannot weld two lines together, which the round-9 version of this could:
  // after removing one `\n` from a `\n\n`, `before` still ends in a newline.
  if (before.endsWith('\n\n') || before.endsWith('\r\n\r\n')) {
    return before.replace(/\r?\n$/, '') + after
  }
  return before + after
}

/**
 * Cut a stray marker line out, taking back only the newline that terminates it.
 *
 * Removing one from each side, as for a block, welded the user's surrounding
 * lines together — the marker sits on its own line between two lines of theirs,
 * and only its own terminator is ours.
 */
function cutLine(content: string, start: number, end: number): string {
  return content.slice(0, start) + content.slice(end).replace(/^\r?\n/, '')
}

export function hasManagedBlock(content: string): boolean {
  return ownedRegions(content).length > 0
}

/**
 * The managed block's body, or null when the file has none.
 *
 * The one reader. The drift checker used to compute this itself with a plain
 * `indexOf`, and the two diverged — the writer maintaining one region while the
 * checker compared another.
 */
export function extractManagedBlock(content: string): string | null {
  const region = maintainedRegion(content)
  if (!region) return null
  return content.slice(region.start + BLOCK_START.length, region.end - BLOCK_END.length).trim()
}

/** How many complete blocks the file holds — more than one is drift. */
/**
 * What state a co-owned file is in, and who can fix it.
 *
 * The one answer to that question. Five surfaces used to work it out for
 * themselves — `sync`, `sync --check`, `doctor`, `status` and `remove`'s
 * preview — and they disagreed in every combination the reviewers tried:
 * `doctor` green while `sync` was about to delete the user's prose; `doctor`
 * failing forever with a remedy that was a no-op; `sync --check` red on a state
 * the writer refuses by design to change, prescribing the command that refuses;
 * a remedy asserting "markers that do not pair up" about a file whose markers
 * all paired. Each was fixed on its own and the next round found another pair
 * that disagreed, because agreement was being maintained by hand.
 *
 * `fixable` is the fact the surfaces actually need: can any command clear this,
 * or does it need a person? A red check whose remedy cannot work is worse than
 * no check, and it is the failure this branch has shipped most often.
 */
/**
 * `torn` is the only one of these that breaks nothing — the block is intact and
 * every command works — so it is the only one weighted as a warning. The others
 * are conditions a person has to see. They are distinct states rather than one
 * shared shape because reusing `torn` for them made both inherit its weight the
 * moment that weight changed.
 */
export type FileState = 'clean' | 'doubled' | 'torn' | 'unreducible' | 'stale' | 'unreadable'

export interface FileDiagnosis {
  state: FileState
  /** True when a command can clear it; false when only a person can. */
  fixable: boolean
  /** What to tell the user. Empty when there is nothing wrong. */
  detail: string
  /** The remedy, as a command when one works and as instructions when none does. */
  fix: string
}

export function diagnoseManagedFile(
  content: string,
  startMarker: string = BLOCK_START,
  endMarker: string = BLOCK_END,
): FileDiagnosis {
  const blocks = blockRegions(content, startMarker, endMarker).length
  const strays = orphanMarkers(content, startMarker, endMarker).length

  if (blocks > 1 && strays > 0) {
    // The writer will not reduce this: cutting a block here can bring a stray
    // start marker next to a stray end marker and sweep the user's own text
    // into the pair. No command will touch it, so no command may claim to.
    return {
      state: 'unreducible',
      fixable: false,
      detail: `holds ${blocks} OpenCastle blocks and ${strays} marker(s) that pair with nothing`,
      fix: 'delete the blocks you do not want, keeping one start/end pair — this one needs a person',
    }
  }
  if (blocks > 1) {
    return {
      state: 'doubled',
      fixable: true,
      detail: `holds ${blocks} OpenCastle blocks`,
      fix: 'opencastle sync',
    }
  }
  if (strays > 0) {
    return {
      state: 'torn',
      fixable: false,
      detail: `has ${strays} OpenCastle marker(s) that pair with nothing`,
      fix:
        'text beside that marker may be stale generated output, and only you can tell —' +
        ' remove it, or restore the missing marker; this one needs a person',
    }
  }
  return { state: 'clean', fixable: true, detail: '', fix: '' }
}

export function countManagedBlocks(content: string): number {
  // Owned, not total. Counting a quoted example as a block made `sync --check`
  // permanently red on a file `collapseExtraBlocks` deliberately will not
  // change — a failure whose prescribed fix could never clear it.
  return ownedRegions(content).length
}

function wrap(body: string): string {
  return `${BLOCK_START}\n\n${body.trim()}\n\n${BLOCK_END}\n`
}

export const BACKUP_SUFFIX = '.opencastle-backup'

/**
 * Keep the previous contents beside a file we are about to change destructively.
 * Taken at most once per run, so a second call cannot discard what the first saved.
 */
const backedUpThisRun = new Set<string>()

async function backUp(path: string, contents: string): Promise<void> {
  // Once per run, so a second destructive step cannot discard what the first
  // saved — but not once ever, which left a stale backup and no copy of what a
  // later command actually replaced.
  if (backedUpThisRun.has(path)) return
  backedUpThisRun.add(path)
  await writeBytes(`${path}${BACKUP_SUFFIX}`, contents)
}

/**
 * Everything that would be left if all of ours were taken out.
 *
 * The same function the uninstall uses, so "does this file hold anything of the
 * user's" is answered the same way it will be acted on. It used to strip only
 * the maintained block and then re-scan for strays — the two-pass shape that
 * could promote a pair of orphans into a region and delete what lay between.
 */
function outsideTheBlock(content: string): string {
  return stripAllBlocks(content)
}

/** Everything outside *every* block. */
function stripAllBlocks(content: string, start = BLOCK_START, end = BLOCK_END): string {
  // What comes out is decided once, from the file as it stands, and the cuts
  // are applied back to front so the offsets stay valid.
  //
  // Re-scanning after each cut looked equivalent and was not. Removing the
  // block can bring a stray start marker above it next to a stray end marker
  // below it, and the next scan reads that pair as a *new* complete block — so
  // the user's text between the two strays went out with it. On a file torn on
  // both sides (a "keep both sides" merge does this) `remove --all` deleted
  // their content and then deleted the file for being empty. Found by seeded
  // round-trip testing; no hand-written fixture had a file torn on both sides
  // at once, which is why eight rounds of review walked past it.
  return applyCuts(content, cutList(content, start, end))
}

interface Cut {
  start: number
  end: number
  /** A marker line with no partner: take the line, never anything around it. */
  lone: boolean
}

/** Every byte range removal is entitled to, computed against `content` alone. */
function cutList(content: string, start = BLOCK_START, end = BLOCK_END): Cut[] {
  return [
    ...blockRegions(content, start, end).map((r) => ({ start: r.start, end: r.end, lone: false })),
    ...orphanMarkers(content, start, end).map((at) => ({
      start: at,
      end: at + markerLengthAt(content, at, start, end),
      lone: true,
    })),
  ].sort((a, b) => b.start - a.start)
}

function applyCuts(content: string, cuts: Cut[]): string {
  let text = content
  for (const cut of cuts) {
    text = cut.lone
      ? cutLine(text, cut.start, cut.end)
      : cutBlock(text, cut.start, cut.end)
  }
  return text
}



/**
 * Write `body` into `path` as a managed block.
 *
 * - No file: write the block alone.
 * - File with a block: replace only the block.
 * - File this tool generated before markers existed: replace it wholesale.
 * - Any other file: keep it verbatim, append the block.
 */
export async function writeManagedBlock(path: string, body: string): Promise<MergeResult> {
  // Byte space from here down — see `asBytes`. Our own block is converted in;
  // the user's half is never decoded, so nothing of theirs can be lost to a
  // codec on the way through.
  const block = asBytes(wrap(body))
  const S = BLOCK_START_BYTES
  const E = BLOCK_END_BYTES

  if (!existsSync(path)) {
    await writeBytes(path, block)
    return { action: 'created', preservedUserContent: false }
  }

  const existing = await readBytes(path)

  // Any complete region is worth examining, not only one we already recognise
  // as ours. Gating on `hasManagedBlock` — "is some region unquoted" — meant a
  // block the fence classifier had mislabelled was never even considered, so
  // the file went straight to the append path and gained a duplicate on every
  // single sync.
  //
  // `current` is what is on disk from here on. The collapse below can write,
  // and the append path further down must build on that rather than on the
  // bytes we read at the top, or it silently reinstates what was collapsed.
  const regions = blockRegions(existing, S, E)
  const orphans = orphanMarkers(existing, S, E)
  if (regions.length > 0) {
    const keep = regions[regions.length - 1]

    // Extra blocks are removed only when the file has no unpaired markers.
    //
    // Cutting a region in a file that also carries strays can bring a stray
    // start marker next to a stray end marker, and the next scan reads that
    // pair as a block of ours — with the user's text between the two strays
    // inside it. `stripAllBlocks` was fixed by deciding its cuts once; that was
    // not enough, because this function wrote the promoted file to disk and the
    // *next* command re-scanned it. Deferring the deletion by one invocation is
    // not preventing it.
    //
    // So: no cut. A file torn on both sides keeps both blocks, `sync --check`
    // reports it, and `doctor` names it as something only a person can resolve
    // — the same policy this module already applies to a lone marker. Guessing
    // has cost the user their prose in three separate rounds.
    const doomed = orphans.length === 0 ? regions.slice(0, -1) : []

    // Every edit computed against `existing` and applied back to front, so no
    // step ever reads a partly-cut file. This is the whole lesson of the last
    // three rounds, stated once.
    type Edit = { start: number; end: number; text?: string }
    const edits: Edit[] = [
      ...doomed.map((r) => ({ start: r.start, end: r.end })),
      { start: keep.start, end: keep.end, text: block.trimEnd() },
    ].sort((a, b) => b.start - a.start)

    let next = existing
    for (const edit of edits) {
      next =
        edit.text === undefined
          ? cutBlock(next, edit.start, edit.end)
          : next.slice(0, edit.start) + edit.text + next.slice(edit.end)
    }

    const hadUserContent = stripAllBlocks(existing, S, E).trim().length > 0
    const damaged = orphans.length > 0 && regions.length > 1
    // Checked outside our own blocks, so the body we are about to write cannot
    // match itself — and checked on this path at all, which it was not. The
    // warning only ever fired while appending, so an upgrade announced the
    // stale half once, at most, and never again on any later sync.
    const stale = carriesLegacyBody(stripAllBlocks(existing, S, E))
    if (next === existing) {
      return {
        action: 'unchanged',
        preservedUserContent: hadUserContent,
        ...(orphans.length > 0 && { orphanMarker: true }),
        ...(damaged && { damaged: true }),
        ...(stale && { staleGeneratedContent: true }),
      }
    }
    if (doomed.length > 0) await backUp(path, existing)
    await writeBytes(path, next)
    return {
      action: doomed.length > 0 ? 'repaired' : 'updated',
      preservedUserContent: hadUserContent,
      ...(orphans.length > 0 && { orphanMarker: true }),
      ...(damaged && { damaged: true }),
      ...(stale && { staleGeneratedContent: true }),
    }
  }

  const current = existing

  if (looksLikeLegacyGenerated(current, S, E)) {
    // The one operation here that discards anything: a previous release wrote
    // this whole file, so replacing it is right — but if someone appended notes
    // below the generated part, there is no marker to tell us where theirs
    // began. Keep a copy next to it rather than being clever, and let the user
    // decide.
    await backUp(path, current)
    await writeBytes(path, block)
    return { action: 'adopted', preservedUserContent: false }
  }

  // The user's file predates OpenCastle. Keep every byte of it — no trimming, no
  // reflowing — and start the block on the next line.
  // Exactly one newline between their content and our block, whether or not
  // their file ended in one. Normalising first ("add a newline if missing, then
  // a blank line") destroyed the information that it did not end in one, so the
  // cut could never restore it and every round trip grew the file by a byte.
  const preamble = current.length > 0 ? `${current}\n` : ''
  await writeBytes(path, preamble + block)
  return {
    action: 'appended',
    preservedUserContent: current.trim().length > 0,
    // A start marker with no partner. We will not guess what it delimits, but
    // the user should know their file has one, because the tool cannot maintain
    // whatever sits below it and will not remove it on uninstall.
    ...(orphanMarkers(current, S, E).length > 0 && { orphanMarker: true }),
    // Their own writing came first, so we appended rather than adopting — but
    // the file also carries our old output somewhere below, and that stale half
    // still names agents and skills that no longer exist. The agent reads both.
    // Adoption exists to prevent exactly that, so when we decline to adopt, the
    // user has to be told what is now doubled.
    //
    // Tested against the file's *opening* line, not against the whole file. A
    // bare substring search fired on a CLAUDE.md that merely mentioned "This
    // file is managed by OpenCastle" in a note to teammates, and the sync
    // wording of the warning then told them to "delete everything above the
    // OpenCastle block that you did not write" — advice that, followed, deletes
    // their file. `looksLikeLegacyGenerated` was hardened against exactly this
    // substring test two functions up; this line was the copy that was not.
    ...(carriesLegacyBody(current) && { staleGeneratedContent: true }),
  }
}

/**
 * Undo only our half of a co-owned file.
 *
 * Removes the managed block. If the user wrote nothing else, the file is deleted;
 * otherwise their content is kept. This is what `init` re-run, the orphaned-install
 * overwrite, and `remove --all` must call instead of unlinking — those three paths
 * treated merged files as wholly generated and destroyed people's own writing.
 */
/**
 * What `stripManagedBlockFromFile` will do to this content, without doing it.
 *
 * Exists so `remove`'s preview and `remove` itself cannot disagree. They did:
 * the preview assumed every co-owned file survives and printed "your own
 * writing stays" over files that were about to be deleted.
 */
/**
 * What `stripManagedBlockFromFile` would do to `path`, reading it the same way.
 *
 * The preview used to decode as UTF-8 while the action read bytes, and the two
 * then disagreed about whether anything of the user's was left: a file whose
 * user half was a single `0xA0` is whitespace to `trim()` in byte space and
 * U+FFFD — not whitespace — in UTF-8 space. The preview promised "your own
 * writing stays" and the action deleted the file, with no backup. One question,
 * one reader, and the reader has to be the one that acts.
 */
export async function predictStripFile(path: string): Promise<{
  outcome: 'stripped' | 'deleted'
  legacyGenerated: boolean
  /** A superseded instruction set of ours would still be there afterwards. */
  staleRemains: boolean
}> {
  const bytes = await readBytes(path)
  const predicted = predictStrip(bytes, BLOCK_START_BYTES, BLOCK_END_BYTES)
  return {
    ...predicted,
    staleRemains:
      predicted.outcome === 'stripped' &&
      carriesLegacyBody(stripAllBlocks(bytes, BLOCK_START_BYTES, BLOCK_END_BYTES)),
  }
}

export function predictStrip(
  content: string,
  start = BLOCK_START,
  end = BLOCK_END,
): {
  outcome: 'stripped' | 'deleted'
  /** True when the file is ours from an older release, so a backup is written. */
  legacyGenerated: boolean
} {
  if (
    blockRegions(content, start, end).length === 0 &&
    looksLikeLegacyGenerated(content, start, end)
  ) {
    return { outcome: 'deleted', legacyGenerated: true }
  }
  // The same reading `stripManagedBlockFromFile` takes, by calling the same
  // function — the two diverged once by sharing a formula instead of a call.
  const remainder = stripAllBlocks(content, start, end)
  return {
    outcome: remainder.trim().length === 0 ? 'deleted' : 'stripped',
    // Only the legacy branch above writes a backup, so only it may claim one.
    legacyGenerated: false,
  }
}

export async function stripManagedBlockFromFile(
  path: string,
): Promise<'deleted' | 'stripped' | 'absent'> {
  if (!existsSync(path)) return 'absent'
  // Bytes, as in the writer: the user's half is handed back exactly as found.
  const existing = await readBytes(path)

  // A start marker with no partner is left exactly where it is, minus the marker
  // line itself.
  //
  // Three attempts at interpreting one have now shipped. Taking the body below
  // it deleted prose someone had written under a marker they merely quoted.
  // Taking nothing left 20KB of stale instructions after an uninstall. Splicing
  // from the marker to the end of our block did both — it deleted the user's
  // rules when the marker sat above the block, and duplicated their paragraphs
  // when it sat below, because the two slices overlapped.
  //
  // "`remove` only runs on an install" justifies claiming the marker line, which
  // is text we wrote. It does not justify claiming bytes on the far side of a
  // block whose boundaries are known exactly. So: complete blocks and marker
  // lines, both unambiguous, and nothing else — in every path, always.
  //
  // The cost is that a genuinely torn file keeps a stale body. That is paid in
  // the open: `doctor` warns and names the file, because only a human can tell
  // their text from ours once the marker is gone.
  // A file a pre-marker release generated in full is unambiguous in a way a torn
  // one is not: it carries no markers at all, and its whole contents are ours.
  if (
    blockRegions(existing, BLOCK_START_BYTES, BLOCK_END_BYTES).length === 0 &&
    looksLikeLegacyGenerated(existing, BLOCK_START_BYTES, BLOCK_END_BYTES)
  ) {
    await backUp(path, existing)
    await rm(path, { force: true })
    return 'deleted'
  }

  const remainder = stripAllBlocks(existing, BLOCK_START_BYTES, BLOCK_END_BYTES)
  if (remainder.trim().length === 0) {
    await rm(path, { force: true })
    return 'deleted'
  }
  // Written exactly as it came out. Appending a newline "to be tidy" meant a
  // file that never ended in one came back a byte longer, which is not what
  // "byte for byte" means.
  await writeBytes(path, remainder)
  return 'stripped'
}

/**
 * Record a root-file merge into a `CopyResults`, once, for every adapter.
 *
 * Five call sites across three adapter families each decided by hand which
 * fields of the merge result to forward, and the answer differed at every one.
 * `repaired` reached three of them, `damaged` reached one, and each omission
 * meant the user was told nothing on the targets that missed it — including
 * about the backup that is the only way to recover a collapse. Both were found
 * by reviewers, one round apart, as separate bugs; they are the same bug, and
 * it is the hand-wiring.
 *
 * A field added to `MergeResult` now reaches every adapter by construction.
 */
export function recordMerge(
  results: {
    copied: string[]
    skipped: string[]
    created: string[]
    adopted?: string[]
    repaired?: string[]
    staleRoots?: string[]
    tornRoots?: string[]
    damagedRoots?: string[]
  },
  path: string,
  merge: MergeResult,
): void {
  if (merge.staleGeneratedContent) (results.staleRoots ??= []).push(path)
  if (merge.orphanMarker) (results.tornRoots ??= []).push(path)
  if (merge.damaged) (results.damagedRoots ??= []).push(path)

  if (merge.action === 'adopted') {
    results.created.push(path)
    ;(results.adopted ??= []).push(path)
  } else if (merge.action === 'repaired') {
    results.created.push(path)
    ;(results.repaired ??= []).push(path)
  } else if (merge.action === 'created') {
    results.created.push(path)
  } else if (merge.action === 'unchanged') {
    results.skipped.push(path)
  } else {
    results.copied.push(path)
  }
}
