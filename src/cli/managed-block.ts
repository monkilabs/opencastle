import { readFile, writeFile, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'

/**
 * Merge generated content into a file the user may already own.
 *
 * Root instruction files — CLAUDE.md, AGENTS.md, GEMINI.md,
 * .github/copilot-instructions.md — are the one place where the user's own
 * writing and the compiler's output share a file. The adapters used to resolve
 * that by skipping: if the file existed, nothing was written. On the exact repo
 * this tool is pitched at — one that already has a CLAUDE.md — that meant the
 * instructions layer silently never installed.
 *
 * A marked block fixes both halves. The user's content is never touched, and
 * the generated section can be replaced on every sync without diffing prose.
 * Same convention as the .gitignore block, so there is one idea to learn.
 */

export const BLOCK_START = '<!-- >>> OpenCastle managed — regenerated by `opencastle sync`, edits here are lost >>> -->'
export const BLOCK_END = '<!-- <<< OpenCastle managed <<< -->'

export type MergeAction =
  | 'created'
  | 'updated'
  | 'appended'
  | 'adopted'
  /** The end marker was missing; the block was rebuilt and the old file backed up. */
  | 'repaired'
  | 'unchanged'

export interface MergeResult {
  action: MergeAction
  /** True when the file held content the user wrote. */
  preservedUserContent: boolean
  /**
   * The file keeps output from an older release above our block, which we could
   * not safely remove because the user's own writing came first.
   */
  staleGeneratedContent?: boolean
  /** The file carries a start marker that opens no block. */
  orphanMarker?: boolean
}

/**
 * Fingerprints of a root file that an OpenCastle release before the markers
 * generated in full.
 *
 * Without this, every existing install's first `sync` would treat its own old
 * output as the user's writing, keep it, and append a second copy underneath —
 * leaving a doubled file whose stale half still advertises agents and skills
 * that no longer exist. These strings only ever came out of this tool.
 */
const LEGACY_GENERATED_MARKERS = [
  'This file is managed by OpenCastle',
  'All conventions, architecture, and project context are embedded below',
  'All conventions, architecture, and project context live in',
]

/** Headers those releases opened the file with. */
const LEGACY_GENERATED_HEADERS = ['# Project Instructions', '# Copilot Instructions']

/** First line with content, ignoring comments that are not our own banner. */
function firstMeaningfulLine(content: string): string {
  for (const raw of content.split('\n')) {
    const line = raw.trim()
    if (!line) continue
    if (line.startsWith('<!--')) {
      if (LEGACY_GENERATED_MARKERS.some((m) => line.includes(m))) return line
      continue
    }
    return line
  }
  return ''
}

/**
 * True only when the file is generated all the way through.
 *
 * Matching a fingerprint anywhere is not enough, in two directions. People edit
 * their generated CLAUDE.md to add house rules at the top — adopting that file
 * deletes the rules, which is the loss the markers exist to prevent wearing a
 * narrower disguise. And a hand-written file can quote "This file is managed by
 * OpenCastle" in a note to teammates without being ours at all. A file that
 * opens with someone else's writing is theirs: the block is appended instead,
 * and the stale generated text stays visible, which is untidy but recoverable.
 */
function looksLikeLegacyGenerated(content: string): boolean {
  const first = firstMeaningfulLine(content)
  const startsGenerated =
    LEGACY_GENERATED_HEADERS.includes(first) ||
    LEGACY_GENERATED_MARKERS.some((m) => first.includes(m))
  return startsGenerated && LEGACY_GENERATED_MARKERS.some((m) => content.includes(m))
}

/** Extract whatever sits outside the managed block. */
export function stripManagedBlock(content: string): string {
  return stripAllBlocks(content)
}

/** Line-start offsets of every occurrence of `marker`, at column 0. */
function markerOffsets(content: string, marker: string): number[] {
  const out: number[] = []
  let from = 0
  for (;;) {
    const at = content.indexOf(marker, from)
    if (at === -1) return out
    if (at === 0 || content[at - 1] === '\n') out.push(at)
    from = at + marker.length
  }
}

export interface BlockRegion {
  /** Offset of BLOCK_START. */
  start: number
  /** Offset just past BLOCK_END. */
  end: number
}

/**
 * Every *complete* block in the file, in order.
 *
 * Complete means a start marker with an end marker after it and no second start
 * marker in between. A lone start marker is not a block and is deliberately not
 * treated as one: two readers disagreed about what it meant — the writer took
 * everything below it as ours and discarded it, the remover took only the marker
 * line — so one deleted line could either weld a stale 20KB body into the user's
 * file forever or delete prose the user had written below a marker they had
 * merely quoted. Neither reading is safe when we cannot tell which is true, so
 * the ambiguity is reported by `orphanMarkers` and acted on by nobody.
 *
 * No markdown analysis. Four rounds went into guessing, from the prose around a
 * marker, whether it was ours; each guess was wrong somewhere, and every mistake
 * ended the same way — conclude there is no block, append another, grow by 20KB
 * a sync. The invariant is enforced instead: exactly one complete block per file.
 */
export function blockRegions(
  content: string,
  startMarker: string = BLOCK_START,
  endMarker: string = BLOCK_END,
): BlockRegion[] {
  const starts = markerOffsets(content, startMarker)
  const ends = markerOffsets(content, endMarker)
  const regions: BlockRegion[] = []

  for (const [i, start] of starts.entries()) {
    const next = starts[i + 1] ?? Infinity
    const end = ends.find((e) => e > start && e < next)
    if (end !== undefined) regions.push({ start, end: end + endMarker.length })
  }
  return regions
}

/** Markers that belong to no block — damage, reported rather than interpreted. */
export function orphanMarkers(
  content: string,
  startMarker: string = BLOCK_START,
  endMarker: string = BLOCK_END,
): number[] {
  // Both orientations. Tracking only unmatched *starts* meant a file torn the
  // other way — end marker surviving, start deleted — was never named by
  // `doctor` and kept its whole generated body through an uninstall, while the
  // `.gitignore` remover swept stray end markers all along. One format, two
  // readers, again.
  const regions = blockRegions(content, startMarker, endMarker)
  const claimedStarts = new Set(regions.map((r) => r.start))
  const claimedEnds = new Set(regions.map((r) => r.end - endMarker.length))
  return [
    ...markerOffsets(content, startMarker).filter((at) => !claimedStarts.has(at)),
    ...markerOffsets(content, endMarker).filter((at) => !claimedEnds.has(at)),
  ].sort((a, b) => a - b)
}

/** How long the marker at `at` is — start and end markers differ in length. */
function markerLengthAt(content: string, at: number): number {
  return content.startsWith(BLOCK_START, at) ? BLOCK_START.length : BLOCK_END.length
}

/** Cut a region out, taking back the newline on each side. Shared with gitignore. */
export function cutBlockRegion(content: string, start: number, end: number): string {
  return cutBlock(content, start, end)
}

/** Cut a marker line out, taking back only its own terminator. */
export function cutMarkerLine(content: string, start: number, end: number): string {
  return cutLine(content, start, end)
}

/**
 * Byte ranges the user has fenced off, computed with our own blocks masked out.
 *
 * The masking is the whole trick, and it is what two earlier attempts at this
 * were missing. Scanning the raw file for fence ranges cannot work: our
 * generated body contains fences of its own, so a fence in the user's prose
 * pairs with one of ours and every pairing after it is nonsense — that is how a
 * real block came to look quoted and CLAUDE.md grew 20KB a sync. Blanking every
 * complete region first (newlines kept, so byte offsets and line numbers are
 * untouched) leaves exactly the user's own fence structure to read.
 *
 * Only *closed* pairs count. An unclosed fence in the user's prose must not cast
 * doubt over the rest of the file; treating it as open-ended is the same bug
 * from the other direction.
 *
 * The local test this replaces — a fence directly above the start marker and
 * directly below the end marker — was fooled by an ordinary file: one ending in
 * a closing fence with no trailing newline puts our start marker directly under
 * that fence, and a fenced example the user later adds below the block closes
 * the trap. Both adjacency tests then pass, we disown our own block, and the
 * file silently carries two sets of instructions that no command will collapse
 * and no uninstall will remove.
 */
function quotedRanges(content: string): Array<{ from: number; to: number }> {
  let masked = content
  for (const r of blockRegions(content)) {
    masked =
      masked.slice(0, r.start) +
      masked.slice(r.start, r.end).replace(/[^\n]/g, ' ') +
      masked.slice(r.end)
  }

  const ranges: Array<{ from: number; to: number }> = []
  const fence = /^\s{0,3}(`{3,}|~{3,})(.*)$/
  let open: { at: number; delim: string } | null = null
  let offset = 0
  for (const line of masked.split('\n')) {
    const m = fence.exec(line)
    if (m) {
      const delim = m[1]
      if (!open) {
        // The range starts after the opening fence's own line.
        open = { at: offset + line.length, delim }
      } else if (delim[0] === open.delim[0] && delim.length >= open.delim.length && !m[2].trim()) {
        // The pair only counts as a quotation if it holds *nothing but*
        // blocks. Because the regions were blanked above, that is exactly
        // "the masked span is whitespace".
        //
        // This is the test that decides it, and the reason is that containment
        // alone does not distinguish the two cases. Someone documenting the
        // convention fences the block and nothing else. An unclosed fence in
        // ordinary prose, by contrast, pairs with the next unrelated fence
        // further down and the span between them is full of the user's own
        // headings and code — with our block merely somewhere in the middle.
        // Reading that as a quotation is what made the tool disown the block it
        // had just written and append another on every sync.
        //
        // The trade: fence our block together with a comment line and we will
        // treat it as ours and overwrite it. That costs one hand-written line
        // in a file the user is deliberately using to document this tool;
        // the alternative costs a duplicated 20KB of instructions in ordinary
        // files, silently, forever.
        if (!masked.slice(open.at, offset).trim()) {
          ranges.push({ from: open.at, to: offset })
        }
        open = null
      }
    }
    offset += line.length + 1
  }
  return ranges
}

function isQuoted(content: string, region: BlockRegion): boolean {
  return quotedRanges(content).some((q) => region.start >= q.from && region.end <= q.to)
}

export function ownedRegions(content: string): BlockRegion[] {
  const regions = blockRegions(content)
  if (regions.length === 0) return []
  const quoted = quotedRanges(content)
  return regions.filter((r) => !quoted.some((q) => r.start >= q.from && r.end <= q.to))
}

/**
 * The region to overwrite, if any.
 *
 * First choice is the last unquoted region. Falling back to a fenced one when
 * it was the only complete block meant `init` spliced 20KB of instructions into
 * the user's own documented example — markdown-quoted, so the instructions
 * layer effectively never installed, which is the failure the managed block
 * exists to prevent.
 *
 * `block` is the second choice, and it is not a heuristic: a region holding
 * byte-for-byte what we are about to write is ours, whatever the fences around
 * it suggest. Fence classification is guesswork at the edges — a user's
 * unclosed fence pairs with some later fence of theirs and swallows a block
 * sitting between the two — and every version of that guess has been wrong in
 * one direction or the other. Recognising our own bytes needs no guess, and the
 * write it authorises is a no-op, so being wrong costs nothing. Without it, a
 * file with an unclosed fence above the block gained a duplicate on every sync.
 */
function maintainedRegion(content: string, block?: string): BlockRegion | null {
  const owned = ownedRegions(content)
  if (owned.length > 0) return owned[owned.length - 1]
  if (!block) return null
  const identical = blockRegions(content).filter(
    (r) => content.slice(r.start, r.end) === block,
  )
  return identical.length === 0 ? null : identical[identical.length - 1]
}

function findBlockStart(content: string): number {
  return maintainedRegion(content)?.start ?? -1
}

/**
 * Cut a block out, taking back only the newline that is certainly ours.
 *
 * The append path writes one newline between the user's content and the block,
 * and the block ends with one. Reclaiming both unconditionally was wrong the
 * moment a file held two blocks: the newline before the *second* one belongs to
 * whatever precedes it, so taking it welded two lines together. In `.gitignore`
 * that turned `.env.local` into part of a comment and stopped it being ignored;
 * in a root file it moved the start marker off column 0, after which
 * `blockRegions` found nothing while `hasManagedBlock` had already said yes, and
 * `sync` threw — having already deleted the framework directories, so the
 * install was left gutted.
 *
 * The block's own trailing newline is always ours. The one before it is taken
 * only when doing so cannot join two lines: when nothing follows, or when what
 * follows starts on its own line anyway.
 */
function cutBlock(content: string, start: number, end: number): string {
  let before = content.slice(0, start)
  const after = content.slice(end).replace(/^\r?\n/, '')
  if (before.endsWith('\n') && (after === '' || after.startsWith('\n'))) {
    before = before.replace(/\r?\n$/, '')
  }
  return before + after
}

/**
 * Cut a stray marker line out, taking back only the newline that terminates it.
 *
 * Removing one from each side, as for a block, welded the user's surrounding
 * lines together — the marker sits on its own line between two lines of theirs,
 * and only its own terminator is ours.
 */
function cutLine(content: string, start: number, end: number): string {
  return content.slice(0, start) + content.slice(end).replace(/^\r?\n/, '')
}

export function hasManagedBlock(content: string): boolean {
  return ownedRegions(content).length > 0
}

/**
 * The managed block's body, or null when the file has none.
 *
 * The one reader. The drift checker used to compute this itself with a plain
 * `indexOf`, and the two diverged — the writer maintaining one region while the
 * checker compared another.
 */
export function extractManagedBlock(content: string): string | null {
  const region = maintainedRegion(content)
  if (!region) return null
  return content.slice(region.start + BLOCK_START.length, region.end - BLOCK_END.length).trim()
}

/** How many complete blocks the file holds — more than one is drift. */
export function countManagedBlocks(content: string): number {
  // Owned, not total. Counting a quoted example as a block made `sync --check`
  // permanently red on a file `collapseExtraBlocks` deliberately will not
  // change — a failure whose prescribed fix could never clear it.
  return ownedRegions(content).length
}

function wrap(body: string): string {
  return `${BLOCK_START}\n\n${body.trim()}\n\n${BLOCK_END}\n`
}

export const BACKUP_SUFFIX = '.opencastle-backup'

/**
 * Keep the previous contents beside a file we are about to change destructively.
 * Taken at most once per run, so a second call cannot discard what the first saved.
 */
const backedUpThisRun = new Set<string>()

async function backUp(path: string, contents: string): Promise<void> {
  // Once per run, so a second destructive step cannot discard what the first
  // saved — but not once ever, which left a stale backup and no copy of what a
  // later command actually replaced.
  if (backedUpThisRun.has(path)) return
  backedUpThisRun.add(path)
  await writeFile(`${path}${BACKUP_SUFFIX}`, contents)
}

/** Everything outside the block we maintain, plus any stray marker lines. */
function outsideTheBlock(content: string): string {
  const region = maintainedRegion(content)
  if (!region) return removeOrphanMarkers(content)
  return removeOrphanMarkers(cutBlock(content, region.start, region.end))
}

/** Everything outside *every* block. */
function stripAllBlocks(content: string): string {
  let text = content
  for (;;) {
    const owned = ownedRegions(text)
    if (owned.length === 0) return removeOrphanMarkers(text)
    const { start, end } = owned[owned.length - 1]
    text = cutBlock(text, start, end)
  }
}

/**
 * Drop stray start markers, and nothing around them.
 *
 * The marker line is unambiguously ours; whatever sits below it is not, so it
 * stays. That is the whole of what we are entitled to do with damage we cannot
 * interpret.
 */
function removeOrphanMarkers(content: string): string {
  let text = content
  for (const at of orphanMarkers(text).reverse()) {
    text = cutLine(text, at, at + markerLengthAt(text, at))
  }
  return text
}

/** Remove every managed block but the last, and any stray start markers. */
function collapseExtraBlocks(content: string): string {
  // Orphan markers are left alone on purpose: damage we will not interpret.
  //
  // A region inside a fenced code block is left alone too. It is the user
  // documenting the convention, not a duplicate of ours — deleting it to satisfy
  // "one block per file" would be destroying their writing to tidy ours. What
  // must never survive is a second *unquoted* block, which is what a merge
  // produces and what the assistant would read as a second set of rules.
  let text = content
  for (;;) {
    const keep = maintainedRegion(text)
    if (!keep) return text
    const doomed = ownedRegions(text).find((r) => r.start !== keep.start)
    if (!doomed) return text
    text = cutBlock(text, doomed.start, doomed.end)
  }
}

/**
 * Write `body` into `path` as a managed block.
 *
 * - No file: write the block alone.
 * - File with a block: replace only the block.
 * - File this tool generated before markers existed: replace it wholesale.
 * - Any other file: keep it verbatim, append the block.
 */
export async function writeManagedBlock(path: string, body: string): Promise<MergeResult> {
  const block = wrap(body)

  if (!existsSync(path)) {
    await writeFile(path, block)
    return { action: 'created', preservedUserContent: false }
  }

  const existing = await readFile(path, 'utf8')

  // Any complete region is worth examining, not only one we already recognise
  // as ours. Gating on `hasManagedBlock` — "is some region unquoted" — meant a
  // block the fence classifier had mislabelled was never even considered, so
  // the file went straight to the append path and gained a duplicate on every
  // single sync.
  //
  // `current` is what is on disk from here on. The collapse below can write,
  // and the append path further down must build on that rather than on the
  // bytes we read at the top, or it silently reinstates what was collapsed.
  let current = existing
  if (blockRegions(existing).length > 0) {
    // Collapse first: any block other than the one we maintain is a duplicate,
    // and leaving it produced a file with two sets of instructions where the
    // stale one named agents that no longer ship.
    const collapsed = collapseExtraBlocks(existing)
    if (collapsed !== existing) {
      await backUp(path, existing)
      await writeFile(path, collapsed)
    }
    current = collapsed

    const region = maintainedRegion(current, block.trimEnd())
    // With no region of ours, every complete block here is the user quoting the
    // convention. Fall through and append below their example.
    if (region) {
      const next =
        current.slice(0, region.start) + block.trimEnd() + current.slice(region.end)
      const hadUserContent = outsideTheBlock(current).trim().length > 0
      if (next === existing) {
        return { action: 'unchanged', preservedUserContent: hadUserContent }
      }
      await writeFile(path, next)
      return {
        action: collapsed !== existing ? 'repaired' : 'updated',
        preservedUserContent: hadUserContent,
      }
    }
  }

  if (looksLikeLegacyGenerated(current)) {
    // The one operation here that discards anything: a previous release wrote
    // this whole file, so replacing it is right — but if someone appended notes
    // below the generated part, there is no marker to tell us where theirs
    // began. Keep a copy next to it rather than being clever, and let the user
    // decide.
    await backUp(path, current)
    await writeFile(path, block)
    return { action: 'adopted', preservedUserContent: false }
  }

  // The user's file predates OpenCastle. Keep every byte of it — no trimming, no
  // reflowing — and start the block on the next line.
  // Exactly one newline between their content and our block, whether or not
  // their file ended in one. Normalising first ("add a newline if missing, then
  // a blank line") destroyed the information that it did not end in one, so the
  // cut could never restore it and every round trip grew the file by a byte.
  const preamble = current.length > 0 ? `${current}\n` : ''
  await writeFile(path, preamble + block)
  return {
    action: 'appended',
    preservedUserContent: current.trim().length > 0,
    // A start marker with no partner. We will not guess what it delimits, but
    // the user should know their file has one, because the tool cannot maintain
    // whatever sits below it and will not remove it on uninstall.
    ...(orphanMarkers(current).length > 0 && { orphanMarker: true }),
    // Their own writing came first, so we appended rather than adopting — but
    // the file also carries our old output somewhere below, and that stale half
    // still names agents and skills that no longer exist. The agent reads both.
    // Adoption exists to prevent exactly that, so when we decline to adopt, the
    // user has to be told what is now doubled.
    ...(LEGACY_GENERATED_MARKERS.some((m) => current.includes(m)) && { staleGeneratedContent: true }),
  }
}

/**
 * Undo only our half of a co-owned file.
 *
 * Removes the managed block. If the user wrote nothing else, the file is deleted;
 * otherwise their content is kept. This is what `init` re-run, the orphaned-install
 * overwrite, and `remove --all` must call instead of unlinking — those three paths
 * treated merged files as wholly generated and destroyed people's own writing.
 */
/**
 * What `stripManagedBlockFromFile` will do to this content, without doing it.
 *
 * Exists so `remove`'s preview and `remove` itself cannot disagree. They did:
 * the preview assumed every co-owned file survives and printed "your own
 * writing stays" over files that were about to be deleted.
 */
export function predictStrip(content: string): {
  outcome: 'stripped' | 'deleted'
  /** True when the file is ours from an older release, so a backup is written. */
  legacyGenerated: boolean
} {
  if (!hasManagedBlock(content) && looksLikeLegacyGenerated(content)) {
    return { outcome: 'deleted', legacyGenerated: true }
  }
  // The same reading `stripManagedBlockFromFile` takes, by calling the same
  // function — the two diverged once by sharing a formula instead of a call.
  const remainder = stripAllBlocks(content)
  return {
    outcome: remainder.trim().length === 0 ? 'deleted' : 'stripped',
    // Only the legacy branch above writes a backup, so only it may claim one.
    legacyGenerated: false,
  }
}

export async function stripManagedBlockFromFile(
  path: string,
): Promise<'deleted' | 'stripped' | 'absent'> {
  if (!existsSync(path)) return 'absent'
  const existing = await readFile(path, 'utf8')

  // A start marker with no partner is left exactly where it is, minus the marker
  // line itself.
  //
  // Three attempts at interpreting one have now shipped. Taking the body below
  // it deleted prose someone had written under a marker they merely quoted.
  // Taking nothing left 20KB of stale instructions after an uninstall. Splicing
  // from the marker to the end of our block did both — it deleted the user's
  // rules when the marker sat above the block, and duplicated their paragraphs
  // when it sat below, because the two slices overlapped.
  //
  // "`remove` only runs on an install" justifies claiming the marker line, which
  // is text we wrote. It does not justify claiming bytes on the far side of a
  // block whose boundaries are known exactly. So: complete blocks and marker
  // lines, both unambiguous, and nothing else — in every path, always.
  //
  // The cost is that a genuinely torn file keeps a stale body. That is paid in
  // the open: `doctor` warns and names the file, because only a human can tell
  // their text from ours once the marker is gone.
  // A file a pre-marker release generated in full is unambiguous in a way a torn
  // one is not: it carries no markers at all, and its whole contents are ours.
  if (!hasManagedBlock(existing) && looksLikeLegacyGenerated(existing)) {
    await backUp(path, existing)
    await rm(path, { force: true })
    return 'deleted'
  }

  const remainder = stripAllBlocks(existing)
  if (remainder.trim().length === 0) {
    await rm(path, { force: true })
    return 'deleted'
  }
  // Written exactly as it came out. Appending a newline "to be tidy" meant a
  // file that never ended in one came back a byte longer, which is not what
  // "byte for byte" means.
  await writeFile(path, remainder)
  return 'stripped'
}
